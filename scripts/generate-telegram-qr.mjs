import { createRequire } from 'node:module';
import { writeFile } from 'node:fs/promises';

// Keep the fixed bot URL scannable without runtime dependencies in the Herdr plugin.
// Regenerate with `node scripts/generate-telegram-qr.mjs` after changing the URL.
const require = createRequire(import.meta.url);
const QRCode = require('qrcode-terminal/vendor/QRCode');
const levels = require('qrcode-terminal/vendor/QRCode/QRErrorCorrectLevel');
const url = 'https://t.me/PeerBandBot';
const qr = new QRCode(-1, levels.L);
qr.addData(url);
qr.make();
const matrix = qr.modules.map((row) => row.map(Number).join(''));
await writeFile(new URL('../herdr/telegram-qr.mjs', import.meta.url),
  '// Generated by scripts/generate-telegram-qr.mjs using qrcode-terminal 0.12.0.\n' +
  `export const TELEGRAM_URL = ${JSON.stringify(url)};\n` +
  `export const TELEGRAM_MATRIX = ${JSON.stringify(matrix, null, 2)};\n`);
